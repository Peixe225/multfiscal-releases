/**
 * Hall das Lendas — carreiras reais curadas (50 lendas do futebol masculino).
 *
 * Números de CARREIRA em jogos OFICIAIS (clubes + seleção principal; sem amistosos, sem base).
 * Fontes públicas (RSSSF, sites oficiais dos clubes/federações, France Football, UEFA/CONMEBOL,
 * Wikipedia com referências). Regras de contagem:
 *   - apps/goals: clube + seleção, jogos oficiais. Para jogadores antigos as bases divergem; o valor
 *     é conservador e o campo vai em `uncertain`.
 *   - assists: só existem registros confiáveis de ~2000 em diante. Sem registro, é uma ESTIMATIVA
 *     arredondada (`assistsEstimated: true`) — a UI mostra "≈".
 *   - ballonDor: Bola de Ouro da France Football (inclui a edição FIFA 2010–2015). Antes de 1995 só
 *     europeus eram elegíveis (Pelé, Maradona, Zico, Garrincha… têm 0 oficial; prêmios honorários
 *     ficam em `notes`).
 *   - goldenBoots: Chuteira de Ouro EUROPEIA (desde 1968).
 *   - ucl: Copa dos Campeões / Champions League. libertadores: Copa Libertadores.
 *   - leagueTitles: campeonatos nacionais de PRIMEIRA divisão (qualquer país; Apertura e Clausura
 *     contam separados; títulos revogados não contam; estaduais não contam).
 *   - otherMajorTitles: outros títulos oficiais grandes — Copa América/Euro, Mundial de Clubes /
 *     Intercontinental, segunda copa continental (Copa da UEFA/Liga Europa, Recopa Europeia,
 *     Sul-Americana/Mercosul/Supercopa) e ouro olímpico. Supercopas, Liga das Nações, Copa das
 *     Confederações e Finalíssima ficam de fora.
 *   - Troca no meio da temporada: o título da liga conta para quem jogou partidas oficiais pelo
 *     campeão naquela temporada antes de sair (ex.: Ronaldo 2006/07, Ronaldinho 2010/11, Suárez
 *     2010/11 pelo Ajax). Títulos de playoff (NASL Soccer Bowl, MLS Cup) contam como título nacional.
 *   - retroBallonDor: Bolas de Ouro do "Nouveau Palmarès" da France Football (2016), que reavaliou as
 *     edições em que só europeus concorriam (Pelé 7, Maradona 2, Garrincha 1, Romário 1). NÃO são
 *     oficiais: a Nota de Legado dá meio crédito a cada uma e a categoria mostra só as oficiais.
 *   - records: marcas notáveis em texto livre (exibição). NÃO entram na nota: a categoria Recordes
 *     usa recordes mundiais ESTRUTURADOS, nas mesmas métricas que uma run pode quebrar — os atuais
 *     (`HISTORIC_RECORDS[].holderIds`) + `pastRecords` (marcas mundiais que a lenda deteve, sozinha
 *     ou dividida, e perdeu depois).
 *   - Jogadores em atividade: números aproximados até o fim de 2025 (`asOf`), marcados em `uncertain`.
 */
import type { Position } from '../../engine/types'

export type LegendField = 'apps' | 'goals' | 'assists' | 'ballonDor' | 'worldCups' | 'goldenBoots' | 'ucl' | 'libertadores' | 'leagueTitles' | 'otherMajorTitles'

export interface LegendClub {
  name: string
  /** Id do clube em src/data/generated/game-data.json, quando o clube existe no jogo. */
  clubId?: string
}

export interface Legend {
  id: string
  /** Nome de exibição (pt-BR). */
  name: string
  fullName: string
  /** Seleção (código FIFA). URS = União Soviética. */
  nationality: string
  /** Chave de bandeira (flag-icons) quando o código FIFA não existe mais no jogo. */
  flag?: string
  position: Position
  born: number
  /** Estreia profissional e último ano como jogador (null = em atividade). */
  years: [number, number | null]
  active?: boolean
  /** Data de corte dos números de quem ainda joga. */
  asOf?: string
  clubs: LegendClub[]
  apps: number
  goals: number
  assists: number
  assistsEstimated: boolean
  ballonDor: number
  worldCups: number
  goldenBoots: number
  ucl: number
  libertadores: number
  leagueTitles: number
  otherMajorTitles: number
  records: string[]
  /** Bolas de Ouro retroativas da France Football (2016) — não oficiais; meio crédito na nota. */
  retroBallonDor?: number
  /** Recordes MUNDIAIS (métricas do jogo) que a lenda deteve e perdeu depois; os atuais saem de HISTORIC_RECORDS. */
  pastRecords?: LegendRecordMetric[]
  /** Campos com fontes divergentes ou em aberto (a UI mostra "≈"). */
  uncertain?: LegendField[]
  notes?: string[]
}

/** Métricas de recorde do motor de legado (src/engine/legacy/records.ts) — as runs quebram as mesmas. */
export type LegendRecordMetric =
  | 'ballonDor'
  | 'ballonDorStreak'
  | 'worldCups'
  | 'goldenBoots'
  | 'ucl'
  | 'libertadores'
  | 'leagueTitles'
  | 'titles'
  | 'goals'
  | 'assists'
  | 'apps'
  | 'goalsPerGame'
  | 'seasonGoals'
  | 'seasonAssists'
  | 'clubGoals'
  | 'nationalGoals'
  | 'youngestBallonDor'

